-- 2026-10-18: «Чеки» филиалов, смена «не учитывать в зарплату», общий отчет весь день.
set lock_timeout = '5s';

-- 1. Смена без учета в зарплату (например, клиент пришёл после закрытия смены).
alter table public.sales_shifts add column if not exists no_pay boolean not null default false;

create or replace function public.sales_shift_set_no_pay(p_shift_id bigint, p_no_pay boolean) returns void
language plpgsql security definer set search_path to 'public' as $fn$
begin
  if not public.is_staff() then raise exception 'Требуется вход сотрудника'; end if;
  update public.sales_shifts set no_pay=coalesce(p_no_pay,false) where id=p_shift_id and status='open';
  if not found then raise exception 'Смена не найдена или уже закрыта'; end if;
end $fn$;
revoke all on function public.sales_shift_set_no_pay(bigint,boolean) from public, anon;
grant execute on function public.sales_shift_set_no_pay(bigint,boolean) to authenticated;

-- 2. Чеки: свободная таблица по филиалам. Сотрудники и админ читают и пишут (филиал выбирает сайт по смене).
create table if not exists public.branch_checks (
  id bigint generated by default as identity primary key,
  branch_id bigint not null references public.sales_branches(id),
  check_date date not null default ((now() at time zone 'Europe/Moscow')::date),
  product text not null default '',
  payment text not null default '',
  deadline text not null default '',
  contacts text not null default '',
  readiness text not null default 'В работе',
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  created_by uuid default auth.uid()
);
create index if not exists branch_checks_branch_idx on public.branch_checks(branch_id, check_date desc, id desc);
alter table public.branch_checks enable row level security;
create policy branch_checks_read on public.branch_checks for select to authenticated using (public.is_staff());
create policy branch_checks_insert on public.branch_checks for insert to authenticated with check (public.is_staff());
create policy branch_checks_update on public.branch_checks for update to authenticated using (public.is_staff()) with check (public.is_staff());
create policy branch_checks_delete on public.branch_checks for delete to authenticated using (public.is_staff());
grant select, insert, update, delete on public.branch_checks to authenticated;
