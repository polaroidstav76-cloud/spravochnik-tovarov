-- Общий отчет: листы из Excel-файла «Отчеты» (выручка по дням, филиалы по месяцам, общий отчет).
-- Применено в Supabase 2026-10-12. Каждый лист — одна строка, клетки лежат в data (jsonb) как в Excel:
-- data.rows["номер строки"]["буква столбца"] = {v: значение, f: формула без «=», s: номер стиля}.
-- Формулы считает сайт (formula.js) и сохраняет готовые значения в v.
-- months — где на листе блок каждого месяца: [{m:'2026-10', from: строка заголовка, to: строка ИТОГО}].
-- Целиком листы видит и меняет только админ (залогиненный пользователь).
-- Сотрудник на открытой смене получает только текущий месяц листа своего филиала через report_branch_month.

create table if not exists public.report_sheets (
  id bigint generated by default as identity primary key,
  sort_order integer not null default 0,
  title text not null,
  branch_id bigint references public.sales_branches(id) on delete set null,  -- для листов «… Выручка»
  data jsonb not null default '{}'::jsonb,
  months jsonb not null default '[]'::jsonb,
  updated_at timestamptz not null default now()
);

alter table public.report_sheets enable row level security;
create policy report_sheets_read on public.report_sheets for select to authenticated using (true);
create policy report_sheets_ins on public.report_sheets for insert to authenticated with check (true);
create policy report_sheets_upd on public.report_sheets for update to authenticated using (true) with check (true);
grant select, insert, update on public.report_sheets to authenticated;
revoke all on public.report_sheets from anon;

-- Отчет филиала за текущий месяц для сотрудника на открытой смене.
create or replace function public.report_branch_month(p_shift_id bigint) returns jsonb
language plpgsql stable security definer set search_path to 'public' as $fn$
declare v_branch bigint; v_sheet public.report_sheets; v_month jsonb; v_rows jsonb; v_key text;
begin
  select branch_id into v_branch from public.sales_shifts where id=p_shift_id and status='open';
  if not found then raise exception 'Смена не найдена или уже закрыта'; end if;
  select * into v_sheet from public.report_sheets where branch_id=v_branch order by sort_order limit 1;
  if not found then return null; end if;
  v_key:=to_char(now() at time zone 'Europe/Moscow','YYYY-MM');
  select m into v_month from jsonb_array_elements(v_sheet.months) m where m->>'m'=v_key limit 1;
  if v_month is null then
    select m into v_month from jsonb_array_elements(v_sheet.months) m where m->>'m'<=v_key order by m->>'m' desc limit 1;
  end if;
  if v_month is null then return null; end if;
  select coalesce(jsonb_object_agg(k,v),'{}'::jsonb) into v_rows
    from jsonb_each(v_sheet.data->'rows') as r(k,v)
    where k::int between (v_month->>'from')::int and (v_month->>'to')::int;
  return jsonb_build_object('title',v_sheet.title,'month',v_month->>'m','from',(v_month->>'from')::int,'to',(v_month->>'to')::int,
    'data',jsonb_build_object('ncols',v_sheet.data->'ncols','cols',v_sheet.data->'cols','styles',v_sheet.data->'styles',
      'merges',v_sheet.data->'merges','heights',v_sheet.data->'heights','rows',v_rows),
    'updated_at',v_sheet.updated_at);
end $fn$;
revoke all on function public.report_branch_month(bigint) from public;
grant execute on function public.report_branch_month(bigint) to anon, authenticated;
