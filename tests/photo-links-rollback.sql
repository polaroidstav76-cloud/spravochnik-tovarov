begin;
select set_config('request.jwt.claims','{"role":"service_role"}',true);
do $$
declare admin_id uuid; employee uuid; slug text; bid bigint; a jsonb; b jsonb; m jsonb; g jsonb; f jsonb; fid uuid:=gen_random_uuid(); rid uuid:=gen_random_uuid(); denied boolean; t text; n integer;
begin
 select user_id into admin_id from public.staff_accounts where active and role='admin' limit 1;
 select user_id into employee from public.staff_accounts where active and role='staff' limit 1;
 select branch_id,pb.slug into bid,slug from photo_private.branches pb join sales_branches sb on sb.id=pb.branch_id where sb.is_active limit 1;
 assert admin_id is not null and bid is not null;
 assert not has_function_privilege('anon','public.photo_links_api(text,jsonb,uuid)','execute');
 assert not has_function_privilege('authenticated','public.photo_links_api(text,jsonb,uuid)','execute');
 assert not has_schema_privilege('anon','photo_private','usage');
 assert not has_schema_privilege('authenticated','photo_private','usage');
 a:=public.photo_links_api('create',jsonb_build_object('phone','8 (900) 000-00-01','branch_id',bid,'request_id',rid,'order_number','photo-test'),admin_id);
 assert a=public.photo_links_api('create',jsonb_build_object('phone','79000000001','branch_id',bid,'request_id',rid),admin_id),'creation retries must return same link';
 t:=a->>'token';assert length(t)=64;
 b:=public.photo_links_api('create',jsonb_build_object('phone','9000000002','slug',slug,'messenger','max','request_id',gen_random_uuid()));
 assert b->>'token'<>t,'different clients must get isolated links';
 perform public.photo_links_api('mode',jsonb_build_object('token',t,'mode','same'));
 g:=public.photo_links_api('group',jsonb_build_object('token',t));
 assert g=public.photo_links_api('group',jsonb_build_object('token',t)),'same size reuses a single group';
 f:=public.photo_links_api('reserve',jsonb_build_object('token',t,'id',fid,'group_id',g->>'id','name','Оригинал.jpg','size',12345));
 assert f->>'name'='Оригинал.jpg';assert f->>'path' like 'disk:/Cloudshop-Client-Photos/%';
 assert (public.photo_links_api('reserve',jsonb_build_object('token',t,'id',fid,'group_id',g->>'id','name','Оригинал.jpg','size',12345))->>'reused')::boolean;
 denied:=false;begin perform public.photo_links_api('finish',jsonb_build_object('token',t));exception when raise_exception then denied:=true;end;assert denied,'pending file blocks completion';
 denied:=false;begin perform public.photo_links_api('file',jsonb_build_object('token',b->>'token','id',fid));exception when raise_exception then denied:=true;end;assert denied,'cross-order file access rejected';
 perform public.photo_links_api('complete_file',jsonb_build_object('token',t,'id',fid));
 denied:=false;begin perform public.photo_links_api('skip',jsonb_build_object('token',t,'id',fid));exception when raise_exception then denied:=true;end;assert denied,'saved originals cannot be skipped';
 denied:=false;begin perform public.photo_links_api('finish',jsonb_build_object('token',t,'snapshot','[]'::jsonb));exception when raise_exception then denied:=true;end;assert denied,'concurrent metadata snapshot must match';
 perform public.photo_links_api('finish',jsonb_build_object('token',t,'comment','Без полей','snapshot',jsonb_build_array(fid::text)));
 m:=public.photo_links_api('manifest',jsonb_build_object('token',t));
 assert m->>'status'='complete' and m->>'comment'='Без полей';
 assert not (m?'phone') and not(m?'token') and not((m->'files'->0)?'path'),'public metadata must not reveal phone or storage paths';
 assert m->>'phone_hint'='0001';
 perform public.photo_links_api('reopen',jsonb_build_object('token',t));
 assert (public.photo_links_api('manifest',jsonb_build_object('token',t))->>'status')='uploading';
 perform public.photo_links_api('reserve',jsonb_build_object('token',t,'id',gen_random_uuid(),'group_id',g->>'id','name','Оригинал.jpg','size',12345));
 assert (select count(*) from photo_private.files where order_id=(a->>'id')::uuid)=2,'duplicate filenames must not overwrite originals';
 perform public.photo_links_api('mode',jsonb_build_object('token',b->>'token','mode','different'));
 g:=public.photo_links_api('group',jsonb_build_object('token',b->>'token','label','10×15'));
 f:=public.photo_links_api('group',jsonb_build_object('token',b->>'token','label','15×21'));
 assert g->>'id'<>f->>'id';
 denied:=false;begin perform public.photo_links_api('configure',jsonb_build_object('token',repeat('x',40),'account_id','test'),employee);exception when sqlstate 'PT403' then denied:=true;end;assert denied,'employees cannot configure storage';
 m:=public.photo_links_api('list',jsonb_build_object('search','photo-test'),admin_id);
 assert jsonb_array_length(m->'orders')=1;
 raise notice 'Photo links: isolation, idempotency, group sizes, pending uploads, reopen, original retention and admin setup passed';
end $$;
rollback;
