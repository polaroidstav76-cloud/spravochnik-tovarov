def private_directory(path):
    path=Path(path);path.mkdir(parents=True,exist_ok=True)
    if os.name!='nt':return
    import csv
    line=subprocess.check_output(['whoami','/user','/fo','csv','/nh'],creationflags=0x08000000).decode(errors='replace').strip()
    sid=list(csv.reader([line]))[0][-1]
    if not re.fullmatch(r'S-1-[0-9-]+',sid):raise UserError('Не удалось определить пользователя Windows.')
    result=subprocess.run(['icacls',str(path),'/inheritance:r','/grant:r',f'*{sid}:(OI)(CI)F','*S-1-5-18:(OI)(CI)F'],capture_output=True,creationflags=0x08000000)
    if result.returncode:raise UserError('Windows не удалось защитить папку настроек.')


def protect(data:bytes,decrypt=False)->bytes:
    if os.name!='nt':raise UserError('Защищённые настройки доступны на Windows.')
    from ctypes import wintypes
    class Blob(ctypes.Structure):
        _fields_=[('cbData',wintypes.DWORD),('pbData',ctypes.POINTER(ctypes.c_char))]
    crypt=ctypes.WinDLL('crypt32',use_last_error=True)
    kernel=ctypes.WinDLL('kernel32',use_last_error=True)
    kernel.LocalFree.argtypes=[ctypes.c_void_p];kernel.LocalFree.restype=ctypes.c_void_p
    srcbuf=ctypes.create_string_buffer(data)
    src=Blob(len(data),ctypes.cast(srcbuf,ctypes.POINTER(ctypes.c_char)));dest=Blob()
    # CRYPTPROTECT_UI_FORBIDDEN; scope is the current Windows user, not the machine.
    if decrypt:
        fn=crypt.CryptUnprotectData
        fn.argtypes=[ctypes.POINTER(Blob),ctypes.c_void_p,ctypes.c_void_p,ctypes.c_void_p,ctypes.c_void_p,wintypes.DWORD,ctypes.POINTER(Blob)]
        result=fn(ctypes.byref(src),None,None,None,None,1,ctypes.byref(dest))
    else:
        fn=crypt.CryptProtectData
        fn.argtypes=[ctypes.POINTER(Blob),wintypes.LPCWSTR,ctypes.c_void_p,ctypes.c_void_p,ctypes.c_void_p,wintypes.DWORD,ctypes.POINTER(Blob)]
        result=fn(ctypes.byref(src),'Cloudshop Print Dispatch',None,None,None,1,ctypes.byref(dest))
    if not result:raise UserError('Не удалось открыть защищённые настройки под этим пользователем Windows.')
    try:return ctypes.string_at(dest.pbData,dest.cbData)
    finally:kernel.LocalFree(ctypes.cast(dest.pbData,ctypes.c_void_p))


class Settings:
    def __init__(self,root):
        self.root=Path(root);private_directory(root)
        self.path=self.root/'settings.dpapi'
    def load(self):
        if not self.path.exists():return {}
        return json.loads(protect(self.path.read_bytes(),decrypt=True))
    def save(self,data):
        tmp=self.path.with_suffix('.tmp')
        tmp.write_bytes(protect(json.dumps(data,ensure_ascii=False).encode()))
        os.replace(tmp,self.path)


class Disk:
    def __init__(self,token):self.token=token
    def request(self,method,endpoint,**params):
        req=urllib.request.Request(API+endpoint+('?' + urllib.parse.urlencode(params) if params else ''),method=method,headers={'Authorization':'OAuth '+self.token})
        try:
            with urllib.request.urlopen(req,timeout=60) as r:
                body=r.read();return json.loads(body) if body else {}
        except urllib.error.HTTPError as e:
            if e.code==409 and method=='PUT' and endpoint=='/resources':return {}
            raise UserError(f'Яндекс Диск вернул ошибку {e.code}. Проверьте доступ и свободное место.') from None
        except (OSError,ValueError):raise UserError('Нет ответа Яндекс Диска. Проверьте интернет.') from None
    def check(self):
        d=self.request('GET','');return d.get('total_space',0)-d.get('used_space',0)
    def remove_generated(self,path):
        # Only paths generated by this program can be removed here.
        if not re.fullmatch(r'disk:/Cloudshop-Print/[a-f0-9]{32}_[a-f0-9]{32}\.zip',path):
            raise UserError('Недопустимый путь архива.')
        try:self.request('DELETE','/resources',path=path,permanently='false')
        except UserError:pass # A failed best-effort cleanup never sends an invalid archive.
    def upload(self,filename,remote):
        filename=Path(filename)
        if self.check()<filename.stat().st_size:raise UserError('На Яндекс Диске недостаточно места. Освободите место и повторите.')
        self.request('PUT','/resources',path='disk:/Cloudshop-Print')
        upload=self.request('GET','/resources/upload',path=remote,overwrite='false')
        href=upload.get('href','')
        parsed=urllib.parse.urlparse(href)
        if parsed.scheme!='https' or not parsed.hostname or not (parsed.hostname.endswith('.yandex.net') or parsed.hostname.endswith('.yandex.ru')):
            raise UserError('Яндекс Диск вернул неизвестный адрес загрузки.')
        # Do not send the OAuth header to the upload host; href already contains a scoped capability.
        try:
            with filename.open('rb') as f:
                req=urllib.request.Request(href,data=f,method='PUT',headers={'Content-Length':str(filename.stat().st_size),'Content-Type':'application/zip'})
                with urllib.request.urlopen(req,timeout=1800) as r:
                    if r.status not in (200,201,202):raise UserError('Не удалось загрузить архив.')
        except (OSError,urllib.error.URLError):raise UserError('Загрузка архива на Диск прервалась. Файлы сохранены.') from None
        metadata=self.request('GET','/resources',path=remote,fields='size,md5')
        with filename.open('rb') as f:checksum=hashlib.file_digest(f,'md5').hexdigest()
        if metadata.get('size')!=filename.stat().st_size or metadata.get('md5')!=checksum:
            raise UserError('Архив на Диске не прошёл проверку целостности.')
        self.request('PUT','/resources/publish',path=remote)
        url=self.request('GET','/resources',path=remote,fields='public_url').get('public_url')
        if not url or not url.startswith('https://'):raise UserError('Не удалось получить ссылку на архив.')
        return url


def smtp_connect(config):
    try:
        client=smtplib.SMTP_SSL('smtp.yandex.ru',465,timeout=60,context=ssl.create_default_context())
        client.login(config['sender'],config['smtp_password'])
        return client
    except (OSError,smtplib.SMTPException):
        raise UserError('Не удалось войти в Яндекс Почту. Проверьте интернет, адрес отправителя, пароль приложения и разрешение почтовых клиентов.') from None


def email_for(config,batch,files):
    msg=EmailMessage()
    msg['From']=config['sender'];msg['To']=batch['recipient']
    msg['Date']=formatdate(localtime=False)
    msg['Message-ID']=f'<cloudshop-print-{batch["id"]}@{config["sender"].split("@")[-1]}>'
    msg['Subject']=('ТЕСТ · ' if batch.get('test_mode',1) else '')+f'Широкоформатная печать · {len(files)} файлов · заказ {batch["id"][:8]}'
    body=['Здравствуйте!', 'ТЕСТОВАЯ ОТПРАВКА. НЕ ПЕРЕДАВАТЬ В ПРОИЗВОДСТВО.' if batch.get('test_mode',1) else '', '',f'Архив с {len(files)} макетами для печати:',batch['link'],'','Состав заказа:']
    body += [f'• {r["branch"]}: {r["name"]}' for r in files]
    body += ['','Файлы в архиве сохранены в оригинале.','Ссылка доступна любому, кто её получил. Не пересылайте её посторонним.']
    msg.set_content('\n'.join(body))
    return msg


def check_dedicated_bot(token,expected_username=''):
    if not re.fullmatch(r'[0-9]+:[A-Za-z0-9_-]+',token):raise UserError('Неверный формат токена бота.')
    try:
        with urllib.request.urlopen('https://api.telegram.org/bot'+token+'/getWebhookInfo',timeout=30) as r:
            value=json.load(r)
        if not value.get('ok'):raise UserError('Telegram не подтвердил токен бота.')
        if value.get('result',{}).get('url'):
            raise UserError('У этого бота уже есть webhook. Создайте отдельного нового бота; работа существующего не изменена.')
        with urllib.request.urlopen('https://api.telegram.org/bot'+token+'/getMe',timeout=30) as r:
            me=json.load(r)
        if not me.get('ok') or not me.get('result',{}).get('is_bot'):raise UserError('Telegram не подтвердил бота.')
        username=me['result'].get('username','')
        if expected_username and username.lower()!=expected_username.lstrip('@').lower():raise UserError('Токен относится к другому боту. Нужен @'+expected_username.lstrip('@')+'.')
        return username
    except UserError:raise
    except Exception:raise UserError('Не удалось проверить токен Telegram. Проверьте интернет и токен.') from None
