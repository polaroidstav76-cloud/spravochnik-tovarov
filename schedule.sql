-- График работы. Применено в Supabase 2026-10-11.
-- Одна таблица на месяц: строки — дни, столбцы — места работы (schedule_columns: филиалы и «Вне офиса»).
-- Смотрят все (сотрудники видят только опубликованные месяцы), меняет только админ (залогиненный пользователь).
-- Правила сотрудников (schedule_rules) и просьбы о выходных (schedule_requests) используются
-- в подсказках и при составлении черновика на следующий месяц (логика на сайте, index.html «График работы»).
-- Пустая клетка хранится как person_id = null, строки не удаляются.

create table if not exists public.schedule_columns (
  id bigint generated by default as identity primary key,
  title text not null,
  branch_id bigint references public.sales_branches(id) on delete set null,
  sort_order integer not null default 0,
  slots smallint not null default 1 check (slots between 1 and 3),       -- сколько человек можно поставить (2-й и 3-й необязательные)
  need_weekday smallint not null default 1 check (need_weekday between 0 and 3),
  need_weekend smallint not null default 1 check (need_weekend between 0 and 3),
  is_active boolean not null default true,
  created_at timestamptz not null default now()
);

create table if not exists public.schedule_rules (
  person_id bigint primary key references public.sales_people(id) on delete cascade,
  in_schedule boolean not null default true,
  color text not null default '#E2E8F0',
  days smallint[] not null default '{}',              -- дни недели 1=пн … 7=вс; пусто = любые
  column_ids bigint[] not null default '{}',          -- где может работать; пусто = везде
  helper_column_ids bigint[] not null default '{}',   -- где ему нужен помощник (второй человек)
  target_shifts integer,                               -- сколько смен в месяц; 0 = ставить только вручную
  max_in_row integer not null default 6,
  note text,
  updated_at timestamptz not null default now()
);

create table if not exists public.schedule_months (
  month date primary key,             -- первое число месяца
  published boolean not null default false,
  updated_at timestamptz not null default now()
);

create table if not exists public.schedule_cells (
  work_date date not null,
  column_id bigint not null references public.schedule_columns(id) on delete cascade,
  slot smallint not null default 1 check (slot between 1 and 3),
  person_id bigint references public.sales_people(id) on delete set null,
  updated_at timestamptz not null default now(),
  primary key (work_date, column_id, slot)
);

create table if not exists public.schedule_requests (
  id bigint generated by default as identity primary key,
  person_id bigint not null references public.sales_people(id) on delete cascade,
  date_from date not null,
  date_to date not null,
  note text,
  is_active boolean not null default true,
  created_at timestamptz not null default now()
);

alter table public.schedule_columns enable row level security;
alter table public.schedule_rules enable row level security;
alter table public.schedule_months enable row level security;
alter table public.schedule_cells enable row level security;
alter table public.schedule_requests enable row level security;

create policy schedule_columns_read on public.schedule_columns for select to anon, authenticated using (true);
create policy schedule_columns_ins on public.schedule_columns for insert to authenticated with check (true);
create policy schedule_columns_upd on public.schedule_columns for update to authenticated using (true) with check (true);
create policy schedule_rules_read on public.schedule_rules for select to anon, authenticated using (true);
create policy schedule_rules_ins on public.schedule_rules for insert to authenticated with check (true);
create policy schedule_rules_upd on public.schedule_rules for update to authenticated using (true) with check (true);
create policy schedule_months_read on public.schedule_months for select to anon, authenticated using (true);
create policy schedule_months_ins on public.schedule_months for insert to authenticated with check (true);
create policy schedule_months_upd on public.schedule_months for update to authenticated using (true) with check (true);
create policy schedule_requests_read on public.schedule_requests for select to anon, authenticated using (true);
create policy schedule_requests_ins on public.schedule_requests for insert to authenticated with check (true);
create policy schedule_requests_upd on public.schedule_requests for update to authenticated using (true) with check (true);
-- Черновик месяца видит только админ.
create policy schedule_cells_read_admin on public.schedule_cells for select to authenticated using (true);
create policy schedule_cells_read_published on public.schedule_cells for select to anon using (
  exists (select 1 from public.schedule_months m where m.month = date_trunc('month', work_date)::date and m.published)
);
create policy schedule_cells_ins on public.schedule_cells for insert to authenticated with check (true);
create policy schedule_cells_upd on public.schedule_cells for update to authenticated using (true) with check (true);

